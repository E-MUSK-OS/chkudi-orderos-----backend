import { z } from "zod";

export const salesInvoiceItemSchema = z.object({
  id: z.string().optional(),
  itemNo: z.coerce.number().default(1),
  sku: z.string().trim().min(1, "SKU is required."),
  particular: z.string().trim().optional().default(""),
  hsn: z.string().trim().optional().nullable(),
  quantity: z.coerce.number().min(1, "Quantity must be at least 1."),
  rate: z.coerce.number().default(0),
  amount: z.coerce.number().optional().default(0),
  discountPercent: z.coerce.number().optional().default(0),
  discountAmount: z.coerce.number().optional().default(0),
  taxableAmount: z.coerce.number().optional().default(0),
  sgstRate: z.coerce.number().optional().default(0),
  sgstAmount: z.coerce.number().optional().default(0),
  cgstRate: z.coerce.number().optional().default(0),
  cgstAmount: z.coerce.number().optional().default(0),
  igstRate: z.coerce.number().optional().default(0),
  igstAmount: z.coerce.number().optional().default(0),
  total: z.coerce.number().optional().default(0),
});

export const createSalesInvoiceSchema = z.object({
  invoiceType: z.string().trim().default("Tax Invoice"),
  invoiceNo: z.string().trim().optional(),
  invoiceDate: z.string().optional().nullable(),
  challanId: z.string().optional().nullable(),
  challanNo: z.string().trim().optional().nullable(),
  challanDate: z.string().optional().nullable(),
  partyId: z.string().optional().nullable(),
  partyGstn: z.string().trim().optional().nullable(),
  stateCode: z.string().trim().optional().nullable(),
  brokerName: z.string().trim().optional().nullable(),
  consigneeName: z.string().trim().optional().nullable(),
  editOn: z.boolean().optional().default(true),

  remarks: z.string().trim().optional().nullable(),
  ewayBillNo: z.string().trim().optional().nullable(),
  expenseOnSales: z.coerce.number().optional().default(0),
  hasReceipt: z.boolean().optional().default(false),
  receivedAmount: z.coerce.number().optional().default(0),
  receiptMode: z.string().trim().optional().nullable(),
  receiptAccount: z.string().trim().optional().nullable(),
  transactionType: z.string().trim().optional().nullable(),
  transactionDate: z.string().optional().nullable(),
  chequeNo: z.string().trim().optional().nullable(),
  bankName: z.string().trim().optional().nullable(),
  applyRoundOff: z.boolean().optional(),

  billingPartyName: z.string().trim().min(1, "Billing Party Name is required."),
  billingAddress: z.string().trim().optional().nullable(),
  billingCity: z.string().trim().optional().nullable(),
  billingState: z.string().trim().optional().nullable(),
  billingPincode: z.string().trim().optional().nullable(),
  billingEmail: z.string().trim().optional().nullable(),
  billingMobile: z.string().trim().optional().nullable(),

  shippingPartyName: z.string().trim().optional().nullable(),
  shippingAddress: z.string().trim().optional().nullable(),
  shippingAddress2: z.string().trim().optional().nullable(),
  shippingCity: z.string().trim().optional().nullable(),
  shippingState: z.string().trim().optional().nullable(),
  shippingPincode: z.string().trim().optional().nullable(),
  shippingContact: z.string().trim().optional().nullable(),
  courierPartner: z.string().trim().optional().nullable(),
  trackingNo: z.string().trim().optional().nullable(),

  totalQuantity: z.coerce.number().optional().default(0),
  totalAmount: z.coerce.number().optional().default(0),
  totalDiscount: z.coerce.number().optional().default(0),
  amountBeforeTax: z.coerce.number().optional().default(0),
  sgstAmount: z.coerce.number().optional().default(0),
  cgstAmount: z.coerce.number().optional().default(0),
  igstAmount: z.coerce.number().optional().default(0),
  totalGst: z.coerce.number().optional().default(0),
  amountAfterTax: z.coerce.number().optional().default(0),
  roundOff: z.coerce.number().optional(),
  netAmount: z.coerce.number().optional(),

  status: z.string().trim().optional().default("Generated"),
  items: z.array(salesInvoiceItemSchema).min(1, "At least one item is required in the invoice."),
});

export const updateSalesInvoiceSchema = createSalesInvoiceSchema.partial();
